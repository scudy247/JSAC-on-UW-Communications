"""Write the Layer-1 alpha x gap sweep configs (branches S and E) plus two long-horizon runs.

Base points: experiments/configs/b_layer1_{S,E}_a16.yaml (same agents, seeds, tau, nu).
Grid: alpha in ALPHAS x gap scale in GAP_SCALES; the gaps scale the arm means (S) or the transmit-power
offsets in dB (E). Rules (fixed here so every point is comparable):
- oracle Trunc-mean / MoM UCB in branch S use eps = (alpha - 1) / 2 (0.3 at alpha = 1.6 as in the base;
  a moment of order 1 + eps must exist, so a fixed eps = 0.3 is impossible at alpha = 1.2); eps = 1 in E;
- ACK threshold = midpoint of the two lowest true means (the base configs used ad-hoc values), so the
  ACK agents see the same relative position at every point.
Long horizon: alpha = 1.6, scale 1, T = 1e5, LONG_SEEDS seeds, both branches.
ACK-threshold sensitivity (THEORY-B G-7): the two ACK agents at alpha = 1.6, scale 1, threshold at fractions
ACK_FRACS between the two lowest true means, agents seeded by name; configs in b_layer1_ack_sens/.

  python -m experiments.make_b_layer1_sweep     # writes experiments/configs/b_layer1_sweep/*.yaml
"""
import copy
from pathlib import Path

import yaml

ALPHAS = [1.2, 1.4, 1.6, 1.8, 1.95]
GAP_SCALES = [0.5, 1.0, 2.0]
LONG_T, LONG_SEEDS = 100_000, 20
ACK_FRACS = [0.25, 0.5, 0.75]
HERE = Path(__file__).resolve().parent / "configs"
OUT = HERE / "b_layer1_sweep"


def point(base, alpha, scale):
    cfg = copy.deepcopy(base)
    cfg["noise"]["alpha"] = alpha
    cfg["ack_threshold"] = {"between_arms": [0, 1], "frac": 0.5}
    if cfg["reward_model"] == "sas":
        cfg["arms"]["means"] = [round(m * scale, 6) for m in base["arms"]["means"]]
        eps = round((alpha - 1) / 2, 6)
        for a in cfg["agents"]:
            if a["type"] in ("trunc_ucb", "mom_ucb"):
                a["params"]["eps"] = eps
    else:
        cfg["arms"]["snr_db"] = [round(s * scale, 6) for s in base["arms"]["snr_db"]]
    br = "S" if cfg["reward_model"] == "sas" else "E"
    cfg["name"] = f"b_l1sw_{br}_a{alpha:g}_g{scale:g}"
    return cfg


def main():
    OUT.mkdir(exist_ok=True)
    names = []
    for br in ("S", "E"):
        base = yaml.safe_load((HERE / f"b_layer1_{br}_a16.yaml").read_text())
        cfgs = [point(base, a, g) for a in ALPHAS for g in GAP_SCALES]
        long = point(base, 1.6, 1.0)
        long.update(name=f"b_l1long_{br}_a1.6", T=LONG_T, n_seeds=LONG_SEEDS)
        for cfg in cfgs + [long]:
            (OUT / f"{cfg['name']}.yaml").write_text(
                "# generated by experiments/make_b_layer1_sweep.py; do not edit by hand\n"
                + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
            names.append(cfg["name"])
    print(f"wrote {len(names)} configs to {OUT}")
    out2 = HERE / "b_layer1_ack_sens"
    out2.mkdir(exist_ok=True)
    for br in ("S", "E"):
        base = yaml.safe_load((HERE / f"b_layer1_{br}_a16.yaml").read_text())
        for f in ACK_FRACS:
            cfg = point(base, 1.6, 1.0)
            cfg["ack_threshold"]["frac"] = f
            cfg["agents"] = [a for a in cfg["agents"] if a["type"] in ("ack_ucb1", "bernoulli_ts")]
            cfg["agent_seeding"] = "name"
            cfg["name"] = f"b_l1ack_{br}_a1.6_f{f:g}"
            (out2 / f"{cfg['name']}.yaml").write_text(
                "# generated by experiments/make_b_layer1_sweep.py; do not edit by hand\n"
                + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
    print(f"wrote {2 * len(ACK_FRACS)} configs to {out2}")


if __name__ == "__main__":
    main()
