"""Write the NIR-UCB v1 checkpoint configs (THEORY-B G-0): same grid and tables as the alpha x gap sweep
(experiments/make_b_layer1_sweep.py; identical seed, T, nu, tau, noise, arms, ACK rule), new agents:
  naive UCB with the oracle sigma (the reference v1 must match),
  naive UCB calibrated at a fixed alpha (2.0 = Gaussian calibration; 1.2 = worst-case calibration): mis-tuned
  whenever the true alpha differs (branch E only; in branch S the naive scale does not depend on alpha),
  ACK Bernoulli TS, NIR-UCB v1 (gauss widths; bernstein widths in branch E only).
Agents seeded by name (G-7).

  python -m experiments.make_b_layer1_v1     # -> experiments/configs/b_layer1_v1/*.yaml
"""
from pathlib import Path

import yaml

from experiments.make_b_layer1_sweep import ALPHAS, GAP_SCALES, point

HERE = Path(__file__).resolve().parent / "configs"
OUT = HERE / "b_layer1_v1"


def agents(br):
    a = [{"name": "UCB (naive, oracle sigma)", "type": "empirical_ucb", "params": {"sigma": "oracle"}}]
    if br == "E":
        a += [{"name": f"UCB (naive, calibrated at alpha={x:g})", "type": "empirical_ucb",
               "params": {"sigma": {"law_alpha": x}}} for x in (2.0, 1.2)]
    a += [{"name": "ACK Bernoulli TS", "type": "bernoulli_ts"},
          {"name": "NIR-UCB v1 (gauss)", "type": "nir_ucb_v1", "params": {"width": "gauss"}}]
    if br == "E":
        a += [{"name": "NIR-UCB v1 (bernstein)", "type": "nir_ucb_v1", "params": {"width": "bernstein"}}]
    return a


def main():
    OUT.mkdir(exist_ok=True)
    n = 0
    for br in ("S", "E"):
        base = yaml.safe_load((HERE / f"b_layer1_{br}_a16.yaml").read_text())
        for al in ALPHAS:
            for g in GAP_SCALES:
                cfg = point(base, al, g)
                cfg["name"] = f"b_l1v1_{br}_a{al:g}_g{g:g}"
                cfg["agents"] = agents(br)
                cfg["agent_seeding"] = "name"
                (OUT / f"{cfg['name']}.yaml").write_text(
                    "# generated by experiments/make_b_layer1_v1.py; do not edit by hand\n"
                    + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
                n += 1
    print(f"wrote {n} configs to {OUT}")


if __name__ == "__main__":
    main()
