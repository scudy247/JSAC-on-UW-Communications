"""Write the Layer-1 goodput configs (THEORY-B G-1/G-2): arms = 3 sub-bands x 5 MCS, reward = goodput,
gamma-hat (pilot EVM) as the soft signal. Grid alpha in ALPHAS x SNR in SNRS (sub-band 0, Gaussian-equivalent);
model defaults from envs/goodput.py (blanking at 10 dB, gap 2 dB, gains 0/-2/-4 dB, 64 pilot + 256 data
symbols, broadband impulses). Agents seeded by name:
  ACK TS and ACK UCB1 per arm (15 arms, success feedback),
  structured gamma-hat UCB calibrated at alpha = 2 (AWGN, what a modem uses) and at alpha = 1.2 (worst case),
  NIR-UCB v1-goodput (calibrated from the noise stream; gauss and bernstein widths),
  threshold AMC on a median-filtered gamma-hat (AWGN thresholds, 90 % target).

  python -m experiments.make_b_layer1_goodput     # -> experiments/configs/b_layer1_goodput/*.yaml
"""
from pathlib import Path

import yaml

from experiments.make_b_layer1_sweep import ALPHAS

SNRS = [5.0, 7.0, 9.0]
HERE = Path(__file__).resolve().parent / "configs"
OUT = HERE / "b_layer1_goodput"
AGENTS = [
    {"name": "ACK TS (per arm)", "type": "goodput_ack_ts"},
    {"name": "ACK UCB1 (per arm)", "type": "goodput_ack_ucb1"},
    {"name": "Structured UCB (AWGN-calibrated)", "type": "structured_goodput", "params": {"calibration": 2.0}},
    {"name": "Structured UCB (calibrated at alpha=1.2)", "type": "structured_goodput", "params": {"calibration": 1.2}},
    {"name": "NIR-UCB v1-goodput (gauss)", "type": "structured_goodput",
     "params": {"calibration": "noise_stream", "width": "gauss"}},
    {"name": "NIR-UCB v1-goodput (bernstein)", "type": "structured_goodput",
     "params": {"calibration": "noise_stream", "width": "bernstein"}},
    {"name": "Threshold AMC (median W=16)", "type": "threshold_amc", "params": {"window": 16}},
]


def config(alpha, snr):
    return {"name": f"b_l1gp_a{alpha:g}_s{snr:g}", "reward_model": "goodput", "seed": 20261002, "n_seeds": 50,
            "T": 10000, "nu": 200, "tau_rt_slots": 3, "noise": {"alpha": alpha, "c": 0.5},
            "goodput": {"snr_db": snr, "mc_packets": 100000, "mc_seed": 12345},
            "agent_seeding": "name", "agents": AGENTS}


def main():
    OUT.mkdir(exist_ok=True)
    n = 0
    for a in ALPHAS:
        for snr in SNRS:
            cfg = config(a, snr)
            (OUT / f"{cfg['name']}.yaml").write_text(
                "# generated by experiments/make_b_layer1_goodput.py; do not edit by hand\n"
                + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))
            n += 1
    print(f"wrote {n} configs to {OUT}")


if __name__ == "__main__":
    main()
